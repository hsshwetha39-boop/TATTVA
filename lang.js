    var LANGS = ["en", "kn", "hi"];
    var STORE_KEY = "tattva-lang";

    var BLOCK_SELECTOR = "p,h1,h2,h3,h4,li,ul,ol,div,section,nav,header,footer,main,form,article";
    var UNIT_TAGS = { h1: 1, h2: 1, h3: 1, h4: 1, p: 1, li: 1, span: 1, a: 1, strong: 1, em: 1, label: 1, button: 1, div: 1, small: 1 };
    var SKIP_TAGS = { script: 1, style: 1, svg: 1, noscript: 1, head: 1 };
    var SKIP_CLASSES = ["logo", "footer-logo", "hero-art", "hero-bubbles", "hero-wave", "lang-switch", "svc-icon", "contact-icon", "scroll-progress"];
    var KEEP_ENGLISH = { "WhatsApp": 1, "Instagram": 1 };

    var units = [];


    /* ---------- helpers ---------- */

    function norm(s) {
        return String(s).replace(/\s+/g, " ").trim();
    }

    function hasLetters(s) {
        return /[A-Za-z\u0900-\u097F\u0C80-\u0CFF]/.test(s);
    }

    function keepAsIs(text) {
        var t = norm(text);
        if (KEEP_ENGLISH[t]) { return true; }
        if (/^@?[\w.+\-]*@[\w.\-]+$/.test(t)) { return true; }   /* email or @handle only */
        return false;
    }

    function hasSkipClass(el) {
        for (var i = 0; i < SKIP_CLASSES.length; i++) {
            if (el.classList && el.classList.contains(SKIP_CLASSES[i])) { return true; }
        }
        return false;
    }

    function hasDirectText(el) {
        for (var n = el.firstChild; n; n = n.nextSibling) {
            if (n.nodeType === 3 && hasLetters(n.nodeValue)) { return true; }
        }
        return false;
    }

    function isUnit(el) {
        var tag = el.nodeName.toLowerCase();
        if (!UNIT_TAGS[tag]) { return false; }
        if (el.querySelector("svg") || el.querySelector(BLOCK_SELECTOR)) { return false; }
        var text = el.textContent;
        if (!hasLetters(text) || keepAsIs(text)) { return false; }
        return hasDirectText(el) || /^(h1|h2|h3|h4|p|li)$/.test(tag);
    }


    /* ---------- find everything that can be translated ---------- */

    function scan(root) {

        for (var n = root.firstChild; n; n = n.nextSibling) {

            if (n.nodeType === 3) {

                /* loose text inside e.g. a button that also holds an icon */
                if (hasLetters(n.nodeValue) && !keepAsIs(n.nodeValue) && n.parentNode !== document.body) {
                    units.push({ kind: "text", node: n, en: n.nodeValue });
                }
                continue;
            }

            if (n.nodeType !== 1) { continue; }

            var tag = n.nodeName.toLowerCase();

            if (SKIP_TAGS[tag] || hasSkipClass(n) || n.hasAttribute("data-i18n-skip")) { continue; }

            if (isUnit(n)) {
                units.push({ kind: "html", el: n, en: n.innerHTML });
            } else {
                scan(n);
            }
        }
    }

    function collect() {

        scan(document.body);

        /* page title + search/social descriptions */
        units.push({ kind: "title", en: document.title });

        ["meta[name='description']", "meta[property='og:title']", "meta[property='og:description']"].forEach(function (sel) {
            var m = document.querySelector(sel);
            if (m) { units.push({ kind: "attr", el: m, attr: "content", en: m.getAttribute("content") }); }
        });

        /* screen-reader labels (menu button, call / WhatsApp buttons) */
        document.querySelectorAll("[aria-label]").forEach(function (el) {
            if (hasSkipClass(el) || (el.closest && el.closest(".logo"))) { return; }
            units.push({ kind: "attr", el: el, attr: "aria-label", en: el.getAttribute("aria-label") });
        });
    }


    /* ---------- apply a language ---------- */

    function lookup(en, lang) {
        if (lang === "en") { return null; }
        var entry = TRANSLATIONS[norm(en)];
        return entry && entry[lang] ? entry[lang] : null;
    }

    function apply(lang) {

        units.forEach(function (u) {

            var tr = lookup(u.en, lang);

            if (u.kind === "html") {
                u.el.innerHTML = tr !== null ? tr : u.en;
            } else if (u.kind === "text") {
                var lead = (u.en.match(/^\s*/) || [""])[0];
                var trail = (u.en.match(/\s*$/) || [""])[0];
                u.node.nodeValue = tr !== null ? lead + tr + trail : u.en;
            } else if (u.kind === "title") {
                document.title = tr !== null ? tr : u.en;
            } else if (u.kind === "attr") {
                u.el.setAttribute(u.attr, tr !== null ? tr : u.en);
            }
        });

        document.documentElement.setAttribute("lang", lang);

        document.querySelectorAll(".lang-switch [data-lang]").forEach(function (b) {
            var on = b.getAttribute("data-lang") === lang;
            b.classList.toggle("is-active", on);
            b.setAttribute("aria-pressed", on ? "true" : "false");
        });
    }

    function remember(lang) {
        try { window.localStorage.setItem(STORE_KEY, lang); } catch (e) { /* storage may be blocked */ }

        try {
            var url = new URL(window.location.href);
            if (lang === "en") { url.searchParams.delete("lang"); } else { url.searchParams.set("lang", lang); }
            window.history.replaceState(null, "", url.pathname + url.search + url.hash);
        } catch (e) { /* ignore */ }
    }

    function setLang(lang) {
        if (LANGS.indexOf(lang) === -1) { lang = "en"; }
        apply(lang);
        remember(lang);
    }

    function startingLang() {
        var fromUrl = null, saved = null;
        try { fromUrl = new URL(window.location.href).searchParams.get("lang"); } catch (e) { /* ignore */ }
        try { saved = window.localStorage.getItem(STORE_KEY); } catch (e) { /* ignore */ }
        if (fromUrl && LANGS.indexOf(fromUrl) !== -1) { return fromUrl; }
        if (saved && LANGS.indexOf(saved) !== -1) { return saved; }
        return "en";
    }


